"""
Корневой conftest бэкенда FREESPORT.

Единственная задача файла — автоматически проставлять маркер `unit` / `integration` /
`performance` по каталогу, в котором лежит тест. Маркер руками ставить не нужно:
правило определяется путём файла. Явный маркер в тесте всегда побеждает автоматический.

Зачем: до появления этого хука 852 из 2699 тестов (31 %) не имели ни одного маркера и
молча выпадали из `make test-unit` / `make test-integration`. Правило «маркер обязателен»
было записано в документации, но ничем не обеспечено, и каждый новый файл без маркера
расширял слепую зону. Теперь разметка не может разойтись с реальностью: путь, не покрытый
правилами, обрывает сбор с ошибкой. Тест вне дерева `backend/` разметить нечем — и здесь
реакция зависит от того, выпал ли он на самом деле: если отбор по `-m` его отбросил, сбор
обрывается `UsageError`, иначе выдаётся `UnmarkedTestWarning` с перечнем таких файлов.

ГРАНИЦА ВОЗМОЖНОСТЕЙ: и предупреждение, и ошибка появляются только там, где этот conftest
загружен, то есть когда rootdir — `backend/` или в аргументах есть хотя бы один путь внутри
него. Вызов вида `pytest /tmp/ext/test_x.py` без единого внутреннего пути даёт другой rootdir,
файл не подхватывается, и ни одна строка отсюда не исполняется. Закрыть этот случай из
conftest нельзя в принципе — он требует плагина, установленного в окружение (`-p`/entry point).

ВАЖНО: pytest загружает этот файл раньше, чем `backend/tests/unit/conftest.py`, который сам
вызывает `settings.configure()`. Поэтому здесь запрещены импорты Django и любое обращение
к настройкам — только pytest и стандартная библиотека.

Подробности и таблица соответствия — `backend/docs/testing-standards.md`, раздел
«Маркеры pytest».
"""

import warnings
from collections import Counter
from pathlib import Path

import pytest

# Каталог `backend/`. Считаем от самого файла, а не от `config.rootpath`: в репозитории есть
# второй, корневой `pytest.ini`, и при запуске с корня rootdir оказывается другим — привязка
# к `__file__` делает разметку независимой от того, откуда запущен pytest.
BACKEND_ROOT = Path(__file__).resolve().parent

# Маркеры, которыми управляет этот хук. Если любой из них уже проставлен в тесте явно
# (`@pytest.mark.*` или `pytestmark`), хук такой тест не трогает.
AUTO_MARKERS = ("unit", "integration", "performance")

# Маркеры, ортогональные автоматическим: ставятся вручную и хуком не управляются. Перечислены
# здесь, потому что от них зависят фильтры CI (`and not slow` в PR-гейтах, `performance or slow`
# в nightly) — список должен быть в одном месте, а не продублирован в тестах.
ORTHOGONAL_MARKERS = ("data_dependent", "slow")

# Каталоги-категории. Ищутся среди сегментов пути и работают на любой глубине, поэтому
# и `tests/integration/`, и `apps/products/tests/integration/`, и гипотетический
# `apps/products/api/tests/integration/` размечаются одинаково.
CATEGORY_DIRS = {
    "unit": "unit",
    "integration": "integration",
    "functional": "integration",
    "regression": "integration",
    "performance": "performance",
}

# Значение по умолчанию для деревьев без каталога-категории: тесты приложения рядом с кодом
# считаются модульными. Асимметрия с `tests/` осознанная — см. testing-standards.md.
DEFAULT_PREFIX_RULES = ((("apps",), "unit"),)

# Путь есть, но ведёт за пределы `backend/`. Отдельное значение, а не второй `None`: «чужое
# дерево» и «у элемента сбора вообще нет файла» — разные ситуации, и в сообщении каждая
# должна быть названа своим именем, а советы для них не совпадают.
OUTSIDE_BACKEND = object()

# Причины, по которым авторазметка неприменима. Держим строками: они попадают и в перечень
# для человека, и в выбор подходящего совета.
REASON_OUTSIDE = "путь вне backend/"
REASON_PATHLESS = "у элемента сбора нет пути к файлу"


class UnmarkedTestWarning(UserWarning):
    """Тест собран, но авторазметка к нему неприменима — из отбора по `-m` он может выпасть."""


def marker_for_path(rel_parts):
    """Возвращает имя маркера для пути теста относительно `backend/`.

    `rel_parts` — кортеж сегментов пути (`Path.parts`), например
    `("tests", "unit", "test_models", "test_product_models.py")`.

    Сначала ищется каталог-категория; берётся самый глубокий, потому что он говорит о тесте
    точнее вышестоящих. Если категории нет — применяются префиксные правила по умолчанию.
    Возвращает `None`, если путь не покрыт ничем.
    """
    for segment in reversed(rel_parts[:-1]):
        marker = CATEGORY_DIRS.get(segment)
        if marker is not None:
            return marker

    for prefix, marker in DEFAULT_PREFIX_RULES:
        if rel_parts[: len(prefix)] == prefix:
            return marker

    return None


def _item_path(item):
    """Путь к файлу элемента сбора или `None`. Единственное место, где он извлекается."""
    return getattr(item, "path", None) or getattr(item, "fspath", None)


def _relative_parts(item):
    """Сегменты пути теста относительно `backend/`.

    Возвращает кортеж сегментов — для теста внутри `backend/`; `OUTSIDE_BACKEND` — если путь
    ведёт наружу (симлинк, `--pyargs`, файл, переданный явным путём) либо не поддаётся
    разрешению; `None` — если у элемента сбора файла нет вовсе. Две последние ситуации
    разметить нечем, но молчать о них нельзя: такой тест может не попасть ни в один прогон
    по `-m`, а это ровно то тихое выпадение, ради которого хук и написан.

    `resolve()` может бросить не только `ValueError` (путь вне дерева), но и `OSError` или
    `RuntimeError` — петля симлинков, превышение MAX_PATH, недопустимые символы. Ловим все
    три: необработанное исключение здесь обрывает весь сбор трейсбеком.
    """
    path = _item_path(item)
    if path is None:
        return None
    try:
        return Path(str(path)).resolve().relative_to(BACKEND_ROOT).parts
    except (ValueError, OSError, RuntimeError):
        return OUTSIDE_BACKEND


def _identify(item):
    """Как назвать тест в сообщении: путь к файлу, а если файла нет — `nodeid`.

    Полагаться на один `nodeid` нельзя: pytest строит его относительно rootdir, и у файла
    снаружи дерева он вырождается в `::test_x` — сообщение без имени файла бесполезно.
    Проверено вручную на `/tmp/exttests/test_outside.py`, переданном вместе с внутренним путём.
    """
    path = _item_path(item)
    if path is not None:
        return str(path)
    return str(getattr(item, "nodeid", None) or "<элемент сбора без пути>")


def _markexpr(config):
    """Выражение из `-m`, либо пустая строка, если отбора по маркеру нет.

    Источник не только командная строка: то же значение может прийти из `addopts` в `pytest.ini`
    (сейчас его нет ни в корневом, ни в `backend/` — это застережено тестом) и из переменной
    окружения `PYTEST_ADDOPTS`. Нам это безразлично: важно само наличие отбора, откуда бы оно
    ни взялось. Пустое и пробельное выражение считаем отсутствием отбора — отфильтровать они
    всё равно ничего не могут.

    Доступ защитный: сломанный, подставной или отсутствующий `config` не должен обрывать сбор
    трейсбеком. Проверка типа здесь не паранойя: `.strip()` на нестроковом значении, положенном
    чужим плагином, уронил бы сбор из второй половины обёртки — то есть ровно тем способом,
    от которого защищаются внешние `getattr`. Цена компромисса — в такой ситуации гейт молча
    деградирует до предупреждения. Выбрано осознанно: обвал всего сбора вреднее пропущенного гейта.
    """
    markexpr = getattr(getattr(config, "option", None), "markexpr", "")
    return markexpr.strip() if isinstance(markexpr, str) else ""


def _apply_markers(items):
    """Проставляет маркеры и возвращает `(unmarkable, unmapped)`.

    `unmarkable` — список `(item, name, reason)` для элементов, которым маркер не проставить;
    сами элементы нужны, чтобы после отбора сверить, кто из них выпал. `unmapped` — множество
    путей внутри `backend/`, не покрытых ни одним правилом.

    Вынесено из хука отдельной функцией намеренно: хук — обёртка вокруг протокола pluggy,
    вызывать его из теста напрямую неудобно, а вся содержательная логика должна проверяться
    без запуска pytest.
    """
    unmarkable = []
    unmapped = set()

    for item in items:
        if any(item.get_closest_marker(name) for name in AUTO_MARKERS):
            continue

        rel_parts = _relative_parts(item)
        if rel_parts is OUTSIDE_BACKEND or rel_parts is None:
            reason = REASON_OUTSIDE if rel_parts is OUTSIDE_BACKEND else REASON_PATHLESS
            unmarkable.append((item, _identify(item), reason))
            continue

        marker = marker_for_path(rel_parts)
        if marker is None:
            unmapped.add("/".join(rel_parts))
            continue

        item.add_marker(getattr(pytest.mark, marker))

    return unmarkable, unmapped


def _listing(entries):
    """Перечень для человека: строка на файл, с причиной и числом тестов в нём.

    Считаем тесты поимённо: несколько тестов одного файла схлопываются в одну строку, и без
    счётчика не видно, сколько именно их затронуто.
    """
    reasons = {}
    counts = Counter()
    for _, name, reason in entries:
        reasons[name] = reason
        counts[name] += 1
    return "\n".join(f"  - {name} ({reasons[name]}, тестов: {counts[name]})" for name in sorted(reasons))


def _advice(entries):
    """Совет, подходящий тем причинам, которые реально встретились.

    «Перенесите файл» бесполезно там, где файла нет вовсе, а сообщение об обрыве сбора —
    единственный канал связи с тем, кто его получит.
    """
    parts = []
    if any(reason == REASON_OUTSIDE for _, _, reason in entries):
        parts.append("Если файл должен размечаться — перенесите его под backend/ или поставьте маркер в файле явно.")
    if any(reason == REASON_PATHLESS for _, _, reason in entries):
        parts.append(
            "Элементу сбора без файла перенос не поможет: маркер такому тесту должен проставлять "
            "тот, кто его порождает, — плагин или параметризация."
        )
    return " ".join(parts)


def _join(*chunks):
    """Склейка непустых кусков через пробел: пустой совет не должен давать двойной пробел."""
    return " ".join(chunk for chunk in chunks if chunk)


def _gate_text(dropped, survived=()):
    """Сообщение для случая, когда тесты действительно выпали из текущего прогона.

    Причину выпадения не называем: узнать, кто именно отбросил элемент, нельзя. При `-m unit --lf`
    или `-m unit -k foo` это мог сделать и не маркерный фильтр, а утверждать «отбросил `-m`»
    там, где виноват `--lf`, значит врать в единственном сообщении, которое увидит человек.

    `survived` — неразмечаемые элементы, которые из прогона не выпали. Их тоже надо назвать:
    обрыв сбора не должен уносить с собой информацию о тех, кто просто остался без маркера.

    Снятие отбора называем локальным выходом, а не выходом вообще: состав фильтров каждого
    прогона CI задан явно и застережён тестами — `test_pr_gates_exclude_performance_and_slow`
    держит три PR-гейта, `test_nightly_runs_what_pr_gates_dropped` — nightly. Советовать
    читателю лога CI «уберите `-m`» значит предлагать ему действие, которое запрещено
    собственными тестами проекта, — и человек уходит искать несуществующий выход.
    """
    tail = _join(
        _advice(dropped),
        "Локально помогает и снятие отбора, если прогон и должен быть полным: без `-m` ничего "
        "не отбрасывается. В CI такого выхода нет — состав фильтров там зафиксирован и "
        "застережён тестами.",
        "См. backend/docs/testing-standards.md, раздел «Маркеры pytest».",
    )
    survivors = ""
    if survived:
        survivors = (
            "\n\nЗаодно: этим тестам маркер тоже не проставить, но из текущего прогона "
            f"они не выпали и сейчас исполняются:\n{_listing(survived)}"
        )
    return (
        "Сбор оборван: перечисленные тесты не размечены и отбором текущего прогона отброшены — "
        "то есть не исполнятся:\n"
        f"{_listing(dropped)}"
        f"{survivors}\n\n"
        f"{tail}"
    )


def _warning_text(entries, dropped=()):
    """Сообщение для мягкого режима — когда обрывать сбор не за что.

    Формулировка зависит от того, выпал ли кто-то на самом деле: без `-m` тест могли отбросить
    по `-k`, `--deselect` или `--lf`, и говорить ему «сейчас они исполняются» было бы неправдой.
    Про будущие прогоны ничего не обещаем: выпадет тест или нет, зависит от выражения, а при
    отрицательном (`-m "not slow"` — фильтр трёх прогонов CI) он отбор проходит.
    """
    if dropped:
        state = (
            "Часть из них отбор текущего прогона отбросил, но `-m` не задан: сузить прогон "
            "по имени или прошлым падениям — осознанный выбор запускающего, и обрывать сбор "
            "своим правилом мы не будем."
        )
    else:
        state = (
            "Сейчас они исполняются — отбор их не отбросил, и обрывать чужой сбор своим "
            "правилом мы не будем. В прогоне, который отберёт тесты по маркеру и отбросит эти, "
            "то же самое станет ошибкой сбора."
        )
    return (
        "Собраны тесты, которым авторазметка не может проставить маркер "
        "unit/integration/performance:\n"
        f"{_listing(entries)}\n\n"
        f"{_join(state, _advice(entries), 'См. backend/docs/testing-standards.md, раздел «Маркеры pytest».')}"
    )


def _unmapped_text(unmapped):
    """Сообщение существующего сторожа для путей внутри `backend/`."""
    listing = "\n".join(f"  - {path}" for path in sorted(unmapped))
    return (
        "Не удалось определить pytest-маркер по каталогу для файлов:\n"
        f"{listing}\n\n"
        "Маркер unit/integration/performance проставляется автоматически по каталогу теста. "
        "Положите тест в каталог-категорию (unit/integration/functional/regression/performance), "
        "поставьте маркер в файле явно или добавьте правило в backend/conftest.py. "
        "Если это временный или служебный файл — его каталог должен быть в norecursedirs (pytest.ini). "
        "См. backend/docs/testing-standards.md, раздел «Маркеры pytest»."
    )


# Обёртка, а не обычная реализация: часть до `yield` выполняется раньше всех обычных хуков,
# то есть до деселекта по `-m` (его делает встроенный плагин `_pytest.mark`), а часть после —
# видит уже отобранный `items`. Это даёт единственный честный способ узнать, выпал ли
# неразмеченный тест: не предсказывать по виду выражения, а посмотреть на результат.
# Предсказание здесь и не работает — при `-m "not slow"` тест без маркеров отбор проходит.
# `tryfirst` больше не нужен: порядок относительно `_pytest.mark` обеспечивает сама обёртка.
@pytest.hookimpl(wrapper=True)
def pytest_collection_modifyitems(config, items):
    """Проставляет маркер по каталогу теста, уважая явно заданные маркеры."""
    unmarkable, unmapped = _apply_markers(items)

    if unmapped:
        # Сторож для путей внутри `backend/` срабатывает здесь, до `yield`, а не после: он не
        # зависит ни от `-m`, ни от отбора, и не должен зависеть от того, доживёт ли выполнение
        # до конца обёртки. Упадёт нижележащий хук (битое выражение `-m`, чужой плагин) — вторая
        # половина обёртки не выполнится вовсе, и сторож молча пропал бы вместе с ней.
        # Предупреждение выдаём раньше обрыва: перечень неразмечаемых иначе уйдёт вместе с ним.
        if unmarkable:
            warnings.warn(_warning_text(unmarkable), UnmarkedTestWarning, stacklevel=1)
        raise pytest.UsageError(_unmapped_text(unmapped))

    result = yield

    if not unmarkable:
        return result

    # Сверяем по `id`, потому что элементы сбора не гарантируют ни хеша, ни равенства.
    # Корректность держится на том, что `unmarkable` хранит сами элементы: пока ссылка жива,
    # её `id` не может достаться другому объекту. Не заменять хранение элементов на хранение
    # одних `id` ради экономии — сверка превратится в лотерею с переиспользованием адресов.
    survived = {id(item) for item in items}
    dropped = [entry for entry in unmarkable if id(entry[0]) not in survived]

    # Гейт требует обоих условий. Одного деселекта мало: без `-m` тест мог быть отброшен
    # по `-k`, `--deselect` или `--lf`, а это осознанный выбор запускающего, не дефект разметки.
    if dropped and _markexpr(config):
        raise pytest.UsageError(_gate_text(dropped, [e for e in unmarkable if e not in dropped]))

    warnings.warn(_warning_text(unmarkable, dropped), UnmarkedTestWarning, stacklevel=1)
    return result
