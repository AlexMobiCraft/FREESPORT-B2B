"""
Общая блокировка массовой записи клиентов (эпик 42, стори 42.3, ревью R18).

Импорт контрагентов 1С держит транзакцию на весь файл и меняет клиентов в
порядке файла, а пересчёт ответственных блокирует строки клиентов по
возрастанию id. Две такие транзакции могут захватить строки навстречу друг
другу и замкнуть цикл ожидания: PostgreSQL откатит одну из них с
``deadlock detected``. Поэтому обе сначала берут одну advisory-блокировку и
идут строго по очереди.

Блокировка транзакционная (``pg_advisory_xact_lock``): PostgreSQL снимает её
при коммите или откате, в том числе при ошибке, — освобождать вручную нечего.
"""

from django.db import connection

# Ключ advisory-блокировки PostgreSQL. Значение произвольное, но общее для
# импорта и пересчёта; другим блокировкам проекта его не давать.
BULK_CLIENTS_LOCK_ID = 4203001


def acquire_bulk_clients_lock() -> None:
    """
    Дождаться общей блокировки и держать её до конца текущей транзакции.

    Вызывать внутри ``transaction.atomic()`` до первой записи клиентов: вне
    транзакции PostgreSQL снял бы блокировку сразу после запроса.
    """
    if not connection.in_atomic_block:
        raise RuntimeError("Блокировка массовой записи клиентов берётся только внутри transaction.atomic()")
    with connection.cursor() as cursor:
        cursor.execute("SELECT pg_advisory_xact_lock(%s)", [BULK_CLIENTS_LOCK_ID])
