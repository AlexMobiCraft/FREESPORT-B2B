"""
Ключи кэша приложения pages.

Вынесены отдельным модулем, потому что используются и во view (запись), и в
сигнале инвалидации (удаление): разъезд имён ключей между этими двумя местами
означает вечно протухший кэш, который никто не сбрасывает.
"""

from django.core.cache import cache

# Префикс ключа полного сериализованного списка опубликованных страниц.
# ВАЖНО: имя отличается от исторического `pages_list` намеренно — под старым
# именем лежал готовый пагинированный ответ (dict), а не список, и после выката
# нового кода такое значение сломало бы пагинацию. Старые записи просто истекут.
PAGES_LIST_CACHE_KEY = "pages_list_serialized"

# Счётчик версии списка. Инвалидация не удаляет данные, а увеличивает версию,
# поэтому каждый сброс кэша меняет и сам ключ данных (см. `pages_list_cache_key`).
PAGES_LIST_VERSION_KEY = "pages_list_version"

# Время жизни кэша списка: сутки. Публикация страницы сбрасывает его сигналом
# немедленно, поэтому длинный TTL задержку видимости не создаёт.
PAGES_LIST_CACHE_TTL = 60 * 60 * 24


def get_pages_list_version() -> int:
    """Текущая версия кэша списка страниц.

    Счётчик хранится без срока жизни (`timeout=None`): он обязан пережить
    данные, которые версионирует, иначе после его исчезновения читатели снова
    начали бы попадать в старый ключ.
    """
    version = cache.get(PAGES_LIST_VERSION_KEY)

    if version is None:
        # `add`, а не `set`: параллельный процесс мог успеть создать счётчик
        # и даже увеличить его — затирать чужое значение единицей нельзя.
        cache.add(PAGES_LIST_VERSION_KEY, 1, None)
        version = cache.get(PAGES_LIST_VERSION_KEY) or 1

    return int(version)


def pages_list_cache_key(version: int) -> str:
    """Ключ данных для конкретной версии списка"""
    return f"{PAGES_LIST_CACHE_KEY}_v{version}"


def bump_pages_list_version() -> int:
    """Переводит кэш списка на новую версию.

    Именно смена версии, а не удаление ключа, закрывает гонку с «поздним
    writer'ом»: запрос, начавший сериализацию до публикации страницы, допишет
    устаревший список под СТАРЫМ ключом, который после инкремента уже никто не
    читает. Удаления ключа для этого недостаточно — поздняя запись возвращала бы
    устаревший список в кэш ещё на сутки.
    """
    try:
        return int(cache.incr(PAGES_LIST_VERSION_KEY))
    except ValueError:
        # Счётчика в кэше нет (истёк или бэкенд был очищен) — начинаем заново.
        cache.set(PAGES_LIST_VERSION_KEY, 1, None)
        return 1
