/**
 * TextSeparator — невидимый текстовый разделитель между соседними узлами карточки.
 *
 * Зачем: `element.textContent` склеивает соседние элементы без пробела, поэтому
 * бейдж, бренд и название товара извлекаются как одно слово («НовинкаBoyBoКапа»).
 * Разделитель разрывает эту склейку (Story 41.8, FR-41-19).
 *
 * Что именно подтверждено замером (2026-09-08, прод + локально), чтобы следующий
 * разработчик не проверял это заново неверным способом:
 *  - Дефект воспроизводится **только** при программном извлечении текста —
 *    `element.textContent`. Так текст читают парсеры и сканеры доступности;
 *    именно этот путь и закрыт правкой, он же замерен до и после.
 *  - Ручное копирование выделения дефект НЕ воспроизводит: браузер сам вставляет
 *    перевод строки на границах блочных элементов, поэтому `Ctrl+C` разделяет слова
 *    и без разделителя. Проверять правку копированием бесполезно — ответ всегда
 *    «всё хорошо», даже на непропатченном коде.
 *  - Произношение экранным диктором правка НЕ улучшает — это замерено, а не
 *    предположено. Chromium AX tree (CDP) и платформенный Windows UIA (тот API,
 *    из которого дикторы строят речь) показали: бейдж, бренд и название были
 *    тремя отдельными текстовыми узлами в отдельных контейнерах уже ДО правки,
 *    а сам разделитель в этих деревьях не появляется вовсе (в AX tree помечен
 *    `ignored:uninteresting`, в UIA отсутствует). Наблюдено ровно это: набор и
 *    порядок текстовых узлов до и после совпадают, разделителя в деревьях нет,
 *    а структура контейнеров отличается на один уровень `[группа]` в UIA
 *    (фрагмент вокруг `<Badge>`). Фактическая речь живого диктора НЕ снималась
 *    (см. `deferred-work.md`), поэтому не ссылаться на этот компонент ни как на
 *    «диктор читает лучше», ни как на «произношение не ухудшилось» — оба
 *    утверждения о речи, а речь не измерена.
 *
 * Почему `sr-only`, а не пробел в потоке: контейнеры описания карточки —
 * flex-колонки (`p-3 flex flex-col` в compact-layout `ProductCard`,
 * `p-4 flex flex-col` в grid-layout). Обычный `<span> </span>` стал бы
 * flex-элементом и добавил строку высотой line-height — вёрстка поехала бы.
 * `sr-only` даёт `position: absolute` — элемент вне потока, внешний вид
 * не меняется. НЕ «упрощать» до голого пробела или текстового узла.
 *
 * Почему рядом с `sr-only` стоят `left-0 top-0`: `sr-only` задаёт
 * `position: absolute`, но не задаёт координат, поэтому элемент встаёт в свою
 * «статическую» позицию — там, где он оказался бы в потоке. В горизонтально
 * прокручиваемой ленте товаров (`/electric`) карточки уезжают вправо за край
 * окна, и разделитель последней карточки оказывался на x≈1532 при ширине окна
 * 1440 — страница получала горизонтальную полосу прокрутки (замер 2026-09-08:
 * `document.body.scrollWidth` 1533 против 1440; удаление разделителей его
 * убирало). `left-0 top-0` прижимают элемент к углу ближайшего позиционированного
 * предка, и вклад в ширину документа исчезает. Координаты НЕ убирать.
 *
 * @example
 * ```tsx
 * <p>{brand.name}</p>
 * <TextSeparator />
 * <h3>{product.name}</h3>
 * ```
 */

import React from 'react';

export const TextSeparator: React.FC = () => <span className="sr-only left-0 top-0"> </span>;

TextSeparator.displayName = 'TextSeparator';
